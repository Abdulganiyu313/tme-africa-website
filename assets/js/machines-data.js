// read from this file automatically — no other file needs to change.
//
// HOW TO ADD A NEW MACHINE
// ------------------------
// Copy one of the objects below (everything between { and },
// including the curly braces), paste it just before the closing
// "];" at the bottom of this file, and edit the values. Keep the
// commas between entries. That's it — reload the page and it's live.
//
// FIELD GUIDE
// ------------------------
// id              — A unique number. Just use the next number up.
// name            — Machine name, shown on the card and in emails.
// category        — Must match one of the filter pill names exactly:
//                    "Lathes", "Milling & Shaping", "Cutting",
//                    "Bending & Rolling", "Pressing & Welding", "Drilling & Grinding",
//                    "Engine & Automotive", "Industrial Equipment",
//                    "Tooling".
//                    
//                    If you want a NEW category, you also need to add
//                    a matching filter button in index.html — ask for
//                    help with that step.
// condition       — "New" or "Used". Shown as a small badge on the
//                    photo (top-left).
// image           — Path to the main thumbnail photo shown on the
//                    catalog card. If the file doesn't exist yet, the
//                    card shows a placeholder automatically — nothing
//                    breaks.
// hasPhoto        — true if "image" above points to a real photo, false
//                    if it's still a placeholder. This controls catalog
//                    ORDER: machines with real photos are shown first,
//                    placeholder-only machines sink to the bottom. The
//                    Heavy-Duty Lathe (id 1) is always shown first no
//                    matter what. When you add a real photo for a
//                    machine that was false, flip this to true so it
//                    moves up with the others.
// gallery         — Click the photo on a catalog card (or the "View
//                    Gallery" button) to open a lightbox with the main
//                    photo plus everything listed here. Leave as an
//                    empty list [] if you don't have extra photos yet.
// videos          — A list of product video paths for this machine.
//                    Shown at the end of the same lightbox. Leave as
//                    an empty list [] if you don't have any yet. Most
//                    machines have none — that's normal.
//
// NAMING CONVENTION FOR PHOTOS & VIDEOS
// ------------------------
// Use the SAME base filename (the part before .jpg) for everything
// that belongs to one machine — that's what makes it obvious which
// files go together when you're managing a lot of them.
//   - Main photo (the "image" field above):  assets/images/lathe.jpg
//   - Extra gallery photos:                  assets/images/lathe-2.jpg, lathe-3.jpg
//   - Videos: just the filename, prefixed with VIDEO_BASE (see below),
//                                             e.g. lathe.mp4, lathe-2.mp4
// Example once you have media for the lathe:
//   gallery: ["assets/images/lathe-2.jpg", "assets/images/lathe-3.jpg"],
//   videos: [`${VIDEO_BASE}lathe.mp4`],
// If a machine has no extra photos or videos, just leave both as
// empty lists [] — nothing breaks, the lightbox simply shows less.
//
// WHERE VIDEOS ACTUALLY LIVE (VIDEO_BASE)
// ------------------------
// Video files are too large to keep in this repo (see assets/videos/
// in .gitignore), so in production they're served from a separate
// video host/CDN. VIDEO_BASE below is the ONE place that controls
// where every video URL points — change it once you have your CDN
// URL and every machine's videos update automatically. Locally, it
// still points at the local assets/videos/ folder so playback works
// on your machine before you've set up hosting.
// specs           — Up to 5 key/value pairs shown on the card. Keep
//                    the labels short (they're column headers). Use
//                    "Control": "Manual" or "Control": "CNC" /
//                    "Automatic" where the machine comes in different
//                    control types.
// tag             — A small badge shown on the photo (top-right),
//                    e.g. "NEW ARRIVAL", "IN STOCK", "FEATURED". Use
//                    null for no badge. This is separate from
//                    "condition" — a used machine can still carry a
//                    tag like "IN STOCK".
// tagColor        — Leave as "orange" (the only style currently used).
// equipmentOption — Must exactly match one of the options in the
//                    Contact form's "Equipment Interest" dropdown in
//                    index.html. Valid values:
//                    "Lathe Machine", "Milling Machine", "Grinding Machine",
//                    "Drilling Machine", "Boring Machine",
